import { setupApp, assert, summary, navigateTo, click } from "./helpers.mjs";
import { markVersesRead } from "../public/js/bible-insights.js";

// The Reading page's chooser: a Book panel grouped as the Hebrew Bible is, a Chapter panel with arrows, and a row of passages.

const { document } = await setupApp();
const content = document.getElementById("content");
const wait = (ms = 150) => new Promise((r) => setTimeout(r, ms));
const refs = (b, c, f, t) => Array.from({ length: t - f + 1 }, (_, i) => `${b}.${c}.${f + i}`);
// some progress to show: all of Ruth 1, part of Ruth 2, and every chapter of Jonah
markVersesRead(refs("Ruth", 1, 1, 22));
markVersesRead(refs("Ruth", 2, 1, 9));
for (const [c, n] of [[1, 16], [2, 11], [3, 10], [4, 11]]) markVersesRead(refs("Jonah", c, 1, n));

navigateTo(document, "bible-reading");
await wait(500);
const nav = () => content.querySelector(".reading-nav");
const bookBtn = () => content.querySelector(".reading-book-btn");
const chBtn = () => content.querySelector(".reading-chapter-btn");
const bookPanel = () => content.querySelector(".reading-book-panel");
const chPanel = () => content.querySelector(".reading-chapter-panel");
const key = (name) => document.dispatchEvent(new document.defaultView.KeyboardEvent("keydown", { key: name, bubbles: true }));

console.log("What is shown");
assert(!!nav() && nav().querySelector(".reading-nav-label").textContent === "Book", "a compact chooser sits above the verses");
assert(bookBtn().textContent.includes("Genesis") && chBtn().textContent.includes("1"), "it names the book and chapter being read");
assert(bookPanel().hidden && chPanel().hidden, "the panels of books and chapters are closed until asked for");
assert(!content.querySelector("select.reading-select") && !content.querySelector(".reading-book-select"), "the old drop-down boxes are gone");
assert([...nav().querySelectorAll(".reading-nav-label")].map((l) => l.textContent).join() === "Book,Chapter,Passages", "the three steps are labelled: Book, Chapter, Passages");

console.log("\nThe book panel");
click(bookBtn());
await wait(50);
assert(!bookPanel().hidden && bookBtn().getAttribute("aria-expanded") === "true", "the button opens the panel and says so");
assert(bookBtn().getAttribute("aria-haspopup") === "dialog" && bookPanel().getAttribute("role") === "dialog" && !!bookPanel().getAttribute("aria-label"), "it is labelled for a screen reader");
const groups = [...bookPanel().querySelectorAll(".reading-pop-group")].map((g) => [g.querySelector(".reading-pop-heading").textContent, [...g.querySelectorAll(".reading-book-item")].length]);
assert(JSON.stringify(groups) === JSON.stringify([["Torah", 5], ["Former Prophets", 6], ["Latter Prophets", 3], ["The Twelve", 12], ["Writings", 13]]), `books are grouped as the Hebrew Bible is: ${JSON.stringify(groups)}`);
assert(bookPanel().querySelector(".reading-book-item.current").dataset.book === "Gen" && bookPanel().querySelector(".reading-book-item.current").getAttribute("aria-current") === "true", "the book being read is marked");
const ruth = bookPanel().querySelector('[data-book="Ruth"]');
const jonah = bookPanel().querySelector('[data-book="Jonah"]');
assert(jonah.classList.contains("done") && /finished/.test(jonah.getAttribute("aria-label")) && !!jonah.querySelector(".reading-tick"), "a finished book (Jonah) is ticked");
assert(!ruth.classList.contains("done") && /percent read/.test(ruth.getAttribute("aria-label")) && parseInt(ruth.querySelector(".reading-book-bar span").style.width) > 0, "a part-read book (Ruth) shows how much of it is read, in the label and a thin bar");
assert(bookPanel().querySelector('[data-book="Lev"] .reading-book-bar span').style.width === "0%", "a book not started shows an empty bar");
key("Escape");
await wait(50);
assert(bookPanel().hidden && bookBtn().getAttribute("aria-expanded") === "false", "Escape closes it");
click(bookBtn());
await wait(50);
click(content.querySelector("h1"));
await wait(50);
assert(bookPanel().hidden, "a click elsewhere closes it");
click(bookBtn());
click(bookBtn());
await wait(50);
assert(bookPanel().hidden, "the button toggles it");
click(bookBtn());
click(chBtn());
await wait(50);
assert(bookPanel().hidden && !chPanel().hidden, "only one panel is open at a time");
key("Escape");
await wait(50);

console.log("\nChoosing a book");
click(bookBtn());
click(bookPanel().querySelector('[data-book="Ruth"]'));
await wait(500);
assert(bookPanel().hidden && bookBtn().textContent.includes("Ruth"), "choosing a book closes the panel and opens it");
assert(chBtn().textContent.includes("2") && /Ruth 2/.test(content.querySelector(".reading-passage-heading").textContent), "it opens at the first chapter not yet read (Ruth 2, the first two being read and one part-read)");
click(bookBtn());
click(bookPanel().querySelector('[data-book="Jonah"]'));
await wait(500);
assert(/Jonah 1/.test(content.querySelector(".reading-passage-heading").textContent), "a finished book opens at its first chapter");

console.log("\nThe chapter panel");
click(bookBtn());
click(bookPanel().querySelector('[data-book="Ruth"]'));
await wait(500);
click(chBtn());
await wait(50);
const items = [...chPanel().querySelectorAll(".reading-chapter-item")];
assert(items.length === 4 && items.map((i) => i.textContent).join() === "1,2,3,4", "Ruth's four chapters are in a grid");
assert(items[0].classList.contains("done") && items[1].classList.contains("partial") && !items[2].classList.contains("done") && !items[2].classList.contains("partial"), "a finished chapter, a part-read one and an unread one look different");
assert(/finished/.test(items[0].getAttribute("aria-label")) && /9 of 23 verses read/.test(items[1].getAttribute("aria-label")), "...and say so to a screen reader");
assert(items[1].classList.contains("current") && items[1].getAttribute("aria-current") === "true", "the chapter being read is marked");
assert(/4 chapters/.test(chPanel().textContent) && /finished/.test(chPanel().querySelector(".reading-pop-legend").textContent), "a heading counts the chapters, and a key explains the marks");
click(items[2]);
await wait(500);
assert(chPanel().hidden && chBtn().textContent.includes("3") && content.querySelector(".reading-verse").dataset.ref === "Ruth.3.1", "choosing a chapter opens it");

console.log("\nThe arrows");
const prev = () => content.querySelector(".reading-prev");
const next = () => content.querySelector(".reading-next");
click(next());
await wait(500);
assert(chBtn().textContent.includes("4") && content.querySelector(".reading-verse").dataset.ref === "Ruth.4.1", "› opens the next chapter");
click(next());
await wait(600);
assert(bookBtn().textContent.includes("Song of Songs") && /Song of Songs 1/.test(content.querySelector(".reading-passage-heading").textContent), "› at the end of a book goes on to the first chapter of the next (Ruth is followed by Song of Songs)");
click(prev());
await wait(600);
assert(bookBtn().textContent.includes("Ruth") && chBtn().textContent.includes("4"), "‹ at the start of a book goes back to the last chapter of the one before");
click(bookBtn());
click(bookPanel().querySelector('[data-book="Gen"]'));
await wait(500);
click(chBtn());
click(chPanel().querySelector('[data-chapter="1"]'));
await wait(300);
assert(prev().disabled && !next().disabled, "‹ is off at the very start of the Bible");
click(bookBtn());
click(bookPanel().querySelector('[data-book="2Chr"]'));
await wait(500);
click(chBtn());
click(chPanel().querySelector('[data-chapter="36"]'));
await wait(500);
assert(!prev().disabled && next().disabled && chBtn().textContent.includes("36"), "› is off at the very end (2 Chronicles 36)");
assert(/Previous chapter/.test(prev().getAttribute("aria-label")) && /Next chapter/.test(next().getAttribute("aria-label")), "the arrows are labelled");

console.log("\nThe Psalms and the passages");
click(bookBtn());
click(bookPanel().querySelector('[data-book="Ps"]'));
await wait(500);
assert([...nav().querySelectorAll(".reading-nav-label")][1].textContent === "Psalm", "the Chapter step is called Psalm in the Psalms");
click(chBtn());
const grid = [...chPanel().querySelectorAll(".reading-chapter-item")];
assert(grid.length === 150 && /Psalm/.test(chPanel().querySelector(".reading-pop-heading").textContent) && /psalms/.test(chPanel().querySelector(".reading-pop-heading").textContent), "all 150 psalms are in the grid");
click(chPanel().querySelector('[data-chapter="119"]'));
await wait(600);
const chips = [...content.querySelectorAll(".reading-chip")];
assert(chips.length >= 15 && chips.every((c) => /^\d+–\d+$/.test(c.querySelector(".reading-chip-range").textContent.trim()) && c.title.startsWith("Psalm 119:")), `Psalm 119 is offered as ${chips.length} passages, each a verse range`);
assert(chips.filter((c) => c.classList.contains("selected")).length === 1 && chips[0].getAttribute("aria-pressed") === "true" && chips[1].getAttribute("aria-pressed") === "false", "the passage being read is marked, and says so");
assert(chips.every((c) => c.querySelector(".reading-chip-know") === null || /^\d+%$/.test(c.querySelector(".reading-chip-know").textContent)), "each passage can show the share of its words you know");
click(chips[2]);
await wait(300);
assert(content.querySelector(".reading-chip.selected").dataset.section === "2" && /Psalm 119:/.test(content.querySelector(".reading-passage-heading").textContent), "choosing a passage shows it");
const sort = content.querySelector(".reading-sort input");
assert(!!sort && /Easiest first/.test(content.querySelector(".reading-sort").textContent), "an option lists the easiest passages first");
click(sort);
await wait(300);
const knowOrder = [...content.querySelectorAll(".reading-chip")].map((c) => { const k = c.querySelector(".reading-chip-know"); return k ? parseInt(k.textContent) : -1; });
assert(knowOrder.every((v, i) => i === 0 || knowOrder[i - 1] >= v), "...in order of the words you know");
click(content.querySelector(".reading-sort input"));
await wait(300);
click(bookBtn());
click(bookPanel().querySelector('[data-book="Jonah"]'));
await wait(500);
click(chBtn());
click(chPanel().querySelector('[data-chapter="4"]'));
await wait(500);
assert(content.querySelectorAll(".reading-chip").length === 1 && !content.querySelector(".reading-sort") && /Passage$/.test([...nav().querySelectorAll(".reading-nav-label")].pop().textContent), "a chapter of up to 12 verses (Jonah 4) is one passage: the step says Passage, and there is no sorting option");

console.log("\nThe heading");
click(bookBtn());
click(bookPanel().querySelector('[data-book="Gen"]'));
await wait(500);
assert(/^Genesis 1:\d+–\d+$/.test(content.querySelector(".reading-passage-heading").textContent), "the passage is named by a plain reference above its verses");
assert(/Chapter 1 has 31 verses · \d+ read · passage 1 of 4/.test(content.querySelector(".reading-where").textContent), "...with the chapter's length, how much is read and which passage this is");

summary();
